"""RAG retrieval evaluation on the SAMPLE corpus, with a not-found threshold sweep.

CAVEATS that must travel with any number from this script: the sample corpus is six short
original sections, and the embedder here is the offline HashingEmbedder (lexical, not
semantic). Hit rates on a corpus this small are easy. A real evaluation needs the actual
course material, bge embeddings, and a validation/test split of real questions."""
from __future__ import annotations

from common import ROOT, environment, save, table

from ostutor.rag.chunk import chunk_pages
from ostutor.rag.index import HashingEmbedder, Index
from ostutor.rag.ingest import load_documents
from ostutor.rag.retrieve import Retriever

IN_TOPIC = [
    ("how do i give execute permission to a script with chmod", "File permissions and chmod"),
    ("what do the r w x bits mean on a directory", "File permissions and chmod"),
    ("what does 755 mean in octal permissions", "File permissions and chmod"),
    ("show a long listing of file permissions", "File permissions and chmod"),
    ("how do I append output to a file instead of overwriting", "Pipes and redirection"),
    ("count the entries in a directory using a pipe", "Pipes and redirection"),
    ("how do I search for a pattern in a file with line numbers", "Pipes and redirection"),
    ("redirect error output separately", "Pipes and redirection"),
    ("what does fork return to the parent and child", "Processes: fork, exec and wait"),
    ("what is a zombie process", "Processes: fork, exec and wait"),
    ("how does a shell run a command", "Processes: fork, exec and wait"),
    ("what signal does kill send by default", "Processes: fork, exec and wait"),
    ("what is stored in an inode", "Files, inodes and paths"),
    ("difference between hard link and symbolic link", "Files, inodes and paths"),
    ("what is an absolute path versus a relative path", "Files, inodes and paths"),
    ("what is a directory in unix", "Files, inodes and paths"),
    ("what is a system call", "System calls"),
    ("what happens when switching from user mode to kernel mode", "System calls"),
    ("give examples of system calls like open and read", "System calls"),
    ("how is printf related to write", "System calls"),
    ("what is a page fault", "Virtual memory and paging"),
    ("what does the TLB do", "Virtual memory and paging"),
    ("what is a page table", "Virtual memory and paging"),
    ("which policies choose the page to evict", "Virtual memory and paging"),
]
OFF_TOPIC = ["who won the football world cup", "what is the capital of australia",
             "best pizza recipe in naples", "how tall is mount everest",
             "write me a poem about autumn", "xyzzy plugh", "stock price of apple today",
             "how do I train a neural network"]


def main() -> dict:
    chunks = chunk_pages(load_documents([ROOT / "data" / "corpus_sample"]))
    index = Index(chunks, HashingEmbedder())
    base = Retriever(index)
    h1 = h3 = 0
    rr = 0.0
    for q, want in IN_TOPIC:
        hits = base.retrieve(q, k=3)
        chapters = [h.chunk.chapter for h in hits]
        h1 += bool(chapters) and chapters[0] == want
        h3 += want in chapters
        rr += 1 / (chapters.index(want) + 1) if want in chapters else 0
    n = len(IN_TOPIC)
    sweep = []
    for bm25_min in (0.0, 0.5, 1.0, 1.5, 2.0, 3.0, 5.0):
        for dense_min in (0.1, 0.25, 0.4):
            r = Retriever(index, bm25_min=bm25_min, dense_min=dense_min)
            missed = sum(not r.retrieve(q) for q, _ in IN_TOPIC)
            leaked = sum(bool(r.retrieve(q)) for q in OFF_TOPIC)
            sweep.append([bm25_min, dense_min, f"{missed}/{n}", f"{leaked}/{len(OFF_TOPIC)}"])
    d = Retriever(index)  # the shipped defaults
    missed = sum(not d.retrieve(q) for q, _ in IN_TOPIC)
    leaked = sum(bool(d.retrieve(q)) for q in OFF_TOPIC)
    md = f"""# RAG retrieval evaluation (sample corpus)

*{environment()}. Generated by `eval/run_rag.py`.*

**Caveat.** {len(chunks)} chunks from six short original sections; offline hashing embedder
(lexical). These numbers show the pipeline works, not how it will do on the real course
material with bge embeddings. Re-run with `OSTUTOR_CORPUS` set and a validation split.

- Questions in the corpus: {n}; off-topic: {len(OFF_TOPIC)}
- hit@1: **{h1}/{n}**, hit@3: **{h3}/{n}**, MRR: **{rr / n:.2f}**
- Shipped thresholds (bm25_min=1.0, dense_min=0.25): in-topic questions wrongly answered
  "not found": **{missed}/{n}**; off-topic questions wrongly answered: **{leaked}/{len(OFF_TOPIC)}**

## Not-found threshold sweep

Choose thresholds on a validation set, not by eye. Each row: in-topic questions rejected
(lower is better) and off-topic questions let through (lower is better).

{table(["bm25_min", "dense_min", "in-topic rejected", "off-topic answered"], sweep)}
"""
    return save("rag", md, {"chunks": len(chunks), "hit1": h1, "hit3": h3, "n": n,
                            "mrr": rr / n, "missed": missed, "leaked": leaked,
                            "off_topic": len(OFF_TOPIC),
                            "headline": f"hit@1 {h1}/{n}, hit@3 {h3}/{n}, off-topic leaked "
                                        f"{leaked}/{len(OFF_TOPIC)}"})


if __name__ == "__main__":
    print(main()["headline"])
