"""Faithfulness evaluation (Build Plan 10.2): how well the mechanical checker separates
faithful from unfaithful narration, and an honest demonstration of what it CANNOT see."""
from __future__ import annotations

import json
from pathlib import Path

from common import ROOT, environment, save, table
from dataset import DATASET

from ostutor.dsl.parser import parse
from ostutor.explorer import analyze
from ostutor.narration.llm import FixtureStore, LLMClient, LLMConfig
from ostutor.narration.pipeline import explain, template_narrate
from ostutor.slice.check import check, tamper_examples


def main() -> dict:
    n = ok = 0
    kinds: dict[str, list[int]] = {}
    blind = []
    for d in DATASET:
        p = parse(d["code"])
        fairs = ("weak", "strong") if isinstance(d["expected"], dict) else ("weak",)
        for f in fairs:
            v = analyze(p.program, loop_unroll=p.loop_unroll, fairness=f)
            narr = template_narrate(p.program, v)
            n += 1
            ok += check(narr, v, p.program).ok
            for kind, bad in tamper_examples(narr, v).items():
                if kind.startswith("invented step") and not v.witness:
                    continue
                rec = kinds.setdefault(kind, [0, 0])
                rec[1] += 1
                rec[0] += not check(bad, v, p.program).ok
            # causal errors that use only valid names, numbers and the right verdict
            names = sorted(p.program["threads"])
            if len(names) >= 2 and v.label != "safe":
                wrong = dict(narr)
                wrong["summary"] = (narr["summary"] + f" This happens because `{names[0]}` is "
                                    f"simply faster than `{names[1]}`.")
                blind.append(check(wrong, v, p.program).ok)

    fixtures = ROOT / "demo_fixtures"
    llm_rows, llm_note = [], ""
    if fixtures.is_dir() and any(fixtures.glob("*.json")):
        client = LLMClient(LLMConfig(api_key=""), fixtures=FixtureStore(fixtures, "replay"))
        for f in sorted((ROOT / "data" / "programs").glob("*.ost")):
            p = parse(f.read_text())
            v = analyze(p.program, loop_unroll=p.loop_unroll)
            e = explain(p.program, v, client)
            llm_rows.append([f.stem, e.source, e.attempts, e.note[:60]])
        used = sum(r[1] == "llm" for r in llm_rows)
        llm_note = (f"Replayed recorded LLM answers for {len(llm_rows)} example programs: "
                    f"**{used} accepted by the checker**, "
                    f"{sum(r[1] == 'template_fallback' for r in llm_rows)} fell back to the "
                    "template (including any with no recorded answer).")
    else:
        llm_note = ("No recorded LLM answers were found (`demo_fixtures/` is empty or absent), "
                    "so **no LLM pass rate or regeneration rate is reported**. Run "
                    "`python -m ostutor.cli warm` with a key, then re-run this script.")

    md = f"""# Faithfulness evaluation

*{environment()}. Generated by `eval/run_faithfulness.py`.*

## Template narration versus the checker

Template narrations accepted by the checker: **{ok}/{n}** (they are built from the trace, so
this is a consistency check of the two components, not evidence about LLM text).

## Tampered narrations (what the checker is designed to reject)

{table(["tampering", "rejected", "total", "rate"],
       [[k, a, b, f"{a / b:.2f}"] for k, (a, b) in kinds.items()])}

## What the checker cannot see (by design)

Narrations that keep every name, number and the verdict correct but add a false *cause*
("this happens because `T1` is simply faster than `T2`") were **accepted in
{sum(blind)}/{len(blind)}** cases. The checker validates facts, not causal reasoning; this
is why the interface says so, and why the plan adds a human audit of a sample and an optional
second-model check. Do not claim the checker detects wrong explanations in general.

## Real LLM output

{llm_note}

{table(["program", "source", "attempts", "note"], llm_rows) if llm_rows else ""}
"""
    return save("faithfulness", md, {
        "template_pass": ok, "template_total": n,
        "tamper": {k: {"rejected": a, "total": b} for k, (a, b) in kinds.items()},
        "blind_spot_accepted": sum(blind), "blind_spot_total": len(blind),
        "llm_rows": llm_rows, "headline": f"templates {ok}/{n}; tamper rejection "
        + ", ".join(f"{a}/{b}" for a, b in kinds.values())})


if __name__ == "__main__":
    print(json.dumps(main()["headline"]))
    Path  # noqa: B018
