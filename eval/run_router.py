"""Router evaluation. The messages below were written separately from the unit tests and the
rules were NOT tuned to them; misroutes are reported, not hidden. They are plausible student
messages written by the authors of this repo, so the rate says little about real traffic."""
from __future__ import annotations

from common import environment, save, table

from ostutor.router.rules import route

CODE = "mutex a\nthread T1:\n  lock a\n  unlock a\nthread T2:\n  lock a\n  unlock a\n"
CASES = [
    (CODE, "analyze_code"),
    ("can you check this?\n" + CODE, "analyze_code"),
    ("```\nthread A:\n  lock m\n  unlock m\n```\nmy mutex program hangs sometimes", "analyze_code"),
    ("Using SJF with arrival times 0 2 4 and bursts 7 4 1, what is the average waiting time?", "simulate"),
    ("Give me the Gantt chart for round robin, quantum 3, P1 burst 10, P2 burst 4", "simulate"),
    ("Run Banker's algorithm: available 3 3 2, max matrix and allocation matrix given", "simulate"),
    ("How many page faults does FIFO give for reference string 1 2 3 4 1 2 5 1 2 3 4 5 with 3 frames", "simulate"),
    ("SCAN disk scheduling, head at 53 moving down, requests 98 183 37 122 14 124 65 67, total movement?", "simulate"),
    ("Priority scheduling with priorities 3 1 2 and bursts 5 3 8, find waiting times", "simulate"),
    ("I got 17 for FCFS average waiting time with bursts 24 3 3, is that right?", "diagnose"),
    ("my answer for the Banker's safe sequence is P0 P1 P2 P3 P4, why is it wrong?", "diagnose"),
    ("I answered 9 page faults for LRU on 7 0 1 2 0 3 0 4 2 3 0 3 2 1 2 0 1 7 0 1", "diagnose"),
    ("my Gantt chart is P1 P2 P3 P1 P2 P1 for round robin quantum 2, what did I do wrong", "diagnose"),
    ("What is the difference between a process and a thread?", "rag"),
    ("Explain demand paging", "rag"),
    ("how do I make a script executable in linux", "rag"),
    ("What does the pipe operator do in bash?", "rag"),
    ("what are the four conditions for deadlock", "rag"),
    ("Why does LRU not suffer from Belady's anomaly?", "rag"),
    ("what is the purpose of a TLB", "rag"),
    ("how does fork work", "rag"),
    ("when should I use a semaphore instead of a mutex", "rag"),
    ("what is starvation in scheduling", "rag"),
    ("define a safe state", "rag"),
    ("Is the C-SCAN algorithm fairer than SCAN?", "rag"),
    ("hi, can you help me with my OS homework", "rag"),
    ("what is the time quantum in round robin", "rag"),
    ("explain how the banker's algorithm avoids deadlock", "rag"),
    ("compute the seek time for sstf, head 50, requests 82 170 43 140 24 16 190", "simulate"),
    ("page replacement: frames 4, references 1 2 3 4 1 2 5 1 2 3 4 5, how many faults for FIFO", "simulate"),
    ("will my code deadlock", "rag"),
    ("my program has a race condition, how do I fix it in general", "rag"),
]


def main() -> dict:
    rows, wrong = [], []
    for msg, want in CASES:
        r = route(msg)
        ok = r.layer == want
        if not ok:
            wrong.append((msg, want, r.layer, r.rules))
        rows.append([msg.replace("\n", " ")[:70], want, r.layer, "yes" if ok else "NO"])
    n = len(CASES)
    agree = n - len(wrong)
    md = f"""# Router evaluation

*{environment()}. Generated by `eval/run_router.py`.*

**Agreement with the intended layer: {agree}/{n}.** Written by the repo authors, rules not
tuned to these messages. This shows the rules behave as designed on plausible messages; it is
not a measurement on real student traffic.

{table(["message (truncated)", "intended", "routed", "agree"], rows)}

## Misroutes

""" + ("\n".join(f"- `{m[:80]!r}`: wanted `{w}`, got `{g}` (rules: {', '.join(r)})"
                  for m, w, g, r in wrong) or "None.")
    return save("router", md, {"cases": n, "agree": agree,
                               "misroutes": [{"message": m, "wanted": w, "got": g}
                                             for m, w, g, _ in wrong],
                               "headline": f"{agree}/{n} agree"})


if __name__ == "__main__":
    print(main()["headline"])
