"""Diagnosis evaluation, SYNTHETIC ONLY (design rule 6).

Matching mutants against answers generated by the same mutants is circular, so nothing here
is a diagnostic-accuracy figure. It checks the plumbing: every mutant is reachable, is
recognised from its own output, correct answers are never blamed on a mutant, and junk is
not matched to one. Accuracy needs REAL student answers (consent + approval)."""
from __future__ import annotations

import random

from common import environment, save, table

from ostutor.diagnosis.engine import diagnose
from ostutor.mutants.catalogue import CATALOGUE, Problem, solve
from ostutor.sims.common import ValidationError


def gen(rng, topic, algo):
    if topic == "cpu":
        procs = [(f"P{i + 1}", rng.randint(0, 6), rng.randint(1, 6), rng.randint(1, 4))
                 for i in range(rng.randint(3, 5))]
        params = {"procs": procs, "quantum": rng.randint(2, 3)}
        if algo == "mlfq":
            params["quanta"] = [2, 3, 5]
        return Problem(topic, algo, params)
    if topic == "paging":
        return Problem(topic, algo, {"refs": [rng.randint(0, 5) for _ in range(rng.randint(8, 20))],
                                     "frames": rng.randint(2, 4)})
    if topic == "disk":
        return Problem(topic, algo, {"requests": [rng.randint(0, 199) for _ in range(rng.randint(4, 8))],
                                     "head": rng.randint(0, 199),
                                     "direction": rng.choice(["up", "down"])})
    return None


BANKER = {"available": [3, 3, 2], "maximum": [[7, 5, 3], [3, 2, 2], [9, 0, 2], [2, 2, 2], [4, 3, 3]],
          "allocation": [[0, 1, 0], [2, 0, 0], [3, 0, 2], [2, 1, 1], [0, 0, 2]]}
BANKER_REQ = {"available": [2, 3, 0], "maximum": BANKER["maximum"], "process": 0,
              "request": [0, 2, 0],
              "allocation": [[0, 1, 0], [3, 0, 2], [3, 0, 2], [2, 1, 1], [0, 0, 2]]}


def main() -> dict:
    rng = random.Random(2026)
    rows, recognised, reachable = [], 0, 0
    for m in CATALOGUE:
        inst = None
        if m.topic == "banker":
            inst = Problem("banker", m.algorithm, BANKER if m.algorithm == "safety" else BANKER_REQ)
            if m.run(inst) == solve(inst).answer:
                inst = None
        else:
            for _ in range(500):
                cand = gen(rng, m.topic, m.algorithm)
                try:
                    if m.run(cand) != solve(cand).answer:
                        inst = cand
                        break
                except ValidationError:
                    continue
        if inst is None:
            rows.append([m.id, "NO", "-", "-"])
            continue
        reachable += 1
        d = diagnose(inst, m.run(inst))
        hit = m.id in d.all_matches
        recognised += hit
        rows.append([m.id, "yes", d.method + (" (ambiguous)" if d.ambiguous else ""),
                     "yes" if hit else "NO"])

    # a correct answer must never be blamed on a mutant; junk should not be matched either
    n_correct = wrongly_blamed = n_junk = junk_matched = 0
    for topic, algos in (("cpu", ["fcfs", "sjf", "srtf", "priority", "rr", "mlfq"]),
                         ("paging", ["fifo", "lru", "opt"]),
                         ("disk", ["fcfs", "sstf", "scan", "cscan", "look", "clook"])):
        for algo in algos:
            for _ in range(15):
                p = gen(rng, topic, algo)
                correct = solve(p).answer
                n_correct += 1
                wrongly_blamed += diagnose(p, correct).method != "correct"
                tokens = sorted(set(correct)) or ["x"]
                junk = [rng.choice(tokens + ["zz"]) for _ in range(len(correct))]
                if junk != correct:
                    n_junk += 1
                    junk_matched += diagnose(p, junk).method == "mutant_match"
    # single-token slips
    slips = slip_ok = 0
    for _ in range(60):
        p = gen(rng, "paging", rng.choice(["fifo", "lru", "opt"]))
        ans = list(solve(p).answer)
        i = rng.randrange(len(ans))
        ans[i] = "H" if ans[i] == "F" else "F"
        d = diagnose(p, ans)
        if d.method in ("edit_distance", "mutant_match"):
            slips += 1
            slip_ok += d.method == "edit_distance" and d.systematic is False
    pairs = {(m.topic, m.algorithm) for m in CATALOGUE}
    md = f"""# Diagnosis evaluation (SYNTHETIC ONLY)

*{environment()}. Generated by `eval/run_diagnosis.py`.*

**This is not a diagnostic-accuracy result.** The wrong answers are generated by the mutants
themselves, so recognising them is circular. It only shows the plumbing works. Accuracy claims
need real, consented student answers (none collected yet).

- Mutants in the catalogue: **{len(CATALOGUE)}**, covering {len(pairs)} (topic, algorithm) pairs
- Mutants with a question that distinguishes them from the correct algorithm: **{reachable}/{len(CATALOGUE)}**
- Mutant output recognised as that mutant (or tied with an identical one): **{recognised}/{reachable}**
- Correct answers never blamed on a mutant: **{n_correct - wrongly_blamed}/{n_correct}**
- Random junk matched to a mutant (should be ~0): **{junk_matched}/{n_junk}**
- One-token slips in paging answers classified as a slip (not a systematic error), among those
  not matching a mutant: **{slip_ok}/{slips}**

{table(["mutant", "reachable", "diagnosis", "recognised"], rows)}
"""
    return save("diagnosis", md, {
        "mutants": len(CATALOGUE), "reachable": reachable, "recognised": recognised,
        "correct_not_blamed": n_correct - wrongly_blamed, "correct_total": n_correct,
        "junk_matched": junk_matched, "junk_total": n_junk, "slips": slips, "slip_ok": slip_ok,
        "synthetic_only": True,
        "headline": f"{recognised}/{reachable} mutants recognised (synthetic, circular)"})


if __name__ == "__main__":
    print(main()["headline"])
