"""Classifier evaluation (Build Plan 10.2): agreement with the labelled set, split by
Tier A (exhaustive), Tier B (symmetry-reduced) and Tier C (sampled) verdicts."""
from __future__ import annotations

import time
from collections import Counter

from common import environment, save, table
from dataset import DATASET

from ostutor.dsl.parser import parse
from ostutor.explorer import analyze, analyze_full, replay
from ostutor.explorer.model import GModel
from ostutor.explorer.pct import analyze_pct
from ostutor.explorer.reduce import make_canon
from ostutor.narration.pipeline import template_narrate
from ostutor.slice.check import check

LABELS = ["safe", "race", "deadlock", "lost_signal", "starvation"]
SEEDS = 20
PCT_RUNS = 200


def cases():
    for d in DATASET:
        exp = d["expected"]
        if isinstance(exp, dict):
            for f in ("weak", "strong"):
                yield d, f, exp[f]
        else:
            yield d, "weak", exp


def main() -> dict:
    rows, conf, a_ok, replay_ok, narr_ok = [], Counter(), 0, 0, 0
    witnesses = 0
    tier_b = []
    c_stats = {lab: [0, 0, 0] for lab in ("deadlock", "race", "lost_signal")}  # [exact, total, any]
    c_false_alarms = 0
    c_safe_runs = 0
    bad_findings = []
    n = 0
    for d, fairness, exp in cases():
        n += 1
        p = parse(d["code"])
        t0 = time.perf_counter()
        v = analyze(p.program, loop_unroll=p.loop_unroll, tier="A", fairness=fairness)
        ms = (time.perf_counter() - t0) * 1000
        conf[(exp, v.label)] += 1
        a_ok += v.label == exp
        if v.witness:
            witnesses += 1
            replay_ok += replay(p.program, v.witness, v.label).ok
        narr = template_narrate(p.program, v)
        narr_ok += check(narr, v, p.program).ok
        if d["name"] == "dl_and_race_together" and v.detail.get("findings") != ["deadlock", "race"]:
            bad_findings.append(d["name"])

        b = "-"
        canon = make_canon(GModel(p.program))
        if canon is not None:
            vb = analyze_full(p.program, loop_unroll=p.loop_unroll, tier="B")[0]
            same_len = (len(vb.witness.steps) if vb.witness else 0) == (
                len(v.witness.steps) if v.witness else 0)
            b_valid = (replay(p.program, vb.witness, vb.label).ok if vb.witness else True)
            tier_b.append({"name": d["name"], "agree": vb.label == v.label and same_len,
                           "replays": b_valid, "states_A": v.states_explored,
                           "states_B": vb.states_explored})
            b = f"{vb.label} ({vb.states_explored})"

        found = 0
        if v.label in c_stats or exp in ("safe", "starvation"):
            for seed in range(SEEDS):
                vc = analyze_pct(p.program, runs=PCT_RUNS, depth=3, seed=seed,
                                 loop_unroll=p.loop_unroll)
                if vc.witness and not replay(p.program, vc.witness, vc.label).ok:
                    raise AssertionError(f"PCT witness failed replay on {d['name']}")
                if exp in c_stats:
                    c_stats[exp][1] += 1
                    found += vc.label == exp
                    c_stats[exp][0] += vc.label == exp
                    c_stats[exp][2] += vc.label in ("deadlock", "race", "lost_signal")
                else:
                    c_safe_runs += 1
                    c_false_alarms += vc.label in ("deadlock", "race", "lost_signal")
        c = f"{found}/{SEEDS}" if exp in c_stats else "-"
        rows.append([d["name"], d["family"], fairness if isinstance(d["expected"], dict) else "",
                     exp, v.label, "yes" if v.label == exp else "NO", v.states_explored,
                     f"{ms:.1f}", b, c])

    per_label = []
    for lab in LABELS:
        tp = conf[(lab, lab)]
        fn = sum(c for (e, g), c in conf.items() if e == lab and g != lab)
        fp = sum(c for (e, g), c in conf.items() if g == lab and e != lab)
        per_label.append([lab, tp + fn, tp, fp, fn,
                          f"{tp / (tp + fp):.2f}" if tp + fp else "n/a",
                          f"{tp / (tp + fn):.2f}" if tp + fn else "n/a"])
    n_b = len(tier_b)
    md = f"""# Classifier evaluation

*{environment()}. Generated by `eval/run_classifier.py`.*

**Read this first.** The expected labels were derived by reasoning (see `eval/dataset.py`),
not by two independent human annotators. So this is **agreement with construction labels on
{len(DATASET)} programs ({n} program/fairness cases)**, not accuracy. Verify every label by
hand (or double-annotate and report disagreements) before quoting precision/recall.

## Tier A (exhaustive search)

- Agreement with the labels: **{a_ok}/{n}**
- Witnesses reproduced by the independent replay: **{replay_ok}/{witnesses}**
- Template narrations accepted by the checker: **{narr_ok}/{n}**
- "Deadlock and race in one program" reports both findings: {"yes" if not bad_findings else "NO"}

{table(["label", "support", "TP", "FP", "FN", "precision", "recall"], per_label)}

## Tier B (symmetry reduction) versus Tier A

Applies to {n_b} cases (programs with a non-trivial symmetry).
Same label and same witness length: **{sum(t["agree"] for t in tier_b)}/{n_b}**;
witnesses replay: **{sum(t["replays"] for t in tier_b)}/{n_b}**;
states A to B: {", ".join(f"{t['name']} {t['states_A']}→{t['states_B']}" for t in tier_b)}.

## Tier C (PCT sampling): {SEEDS} seeds x {PCT_RUNS} runs, depth 3

{table(["expected bug", "batches", "found some failure", "exact label"],
       [[k, b, f"{an}/{b}", f"{a}/{b}"] for k, (a, b, an) in c_stats.items()])}

PCT stops at the FIRST failure it finds, so a program with several failure kinds may report
a different (also real, replay-verified) one; "exact label" counts only the expected kind.

False alarms on programs labelled safe or starvation (Tier C only looks for deadlock, race
and lost signal): **{c_false_alarms}/{c_safe_runs}** sampled batches. Tier C never returns
"safe": a batch that finds nothing is labelled `none_found`/`sampled`.

## Per-program results

{table(["program", "family", "fairness", "expected", "Tier A", "agree", "states", "ms",
        "Tier B (states)", "Tier C found"], rows)}
"""
    return save("classifier", md, {
        "cases": n, "programs": len(DATASET), "tier_a_agree": a_ok, "replay_ok": replay_ok,
        "witnesses": witnesses, "narration_ok": narr_ok, "tier_b": tier_b,
        "tier_c": {k: {"exact": a, "total": b, "any_failure": an} for k, (a, b, an) in c_stats.items()},
        "tier_c_false_alarms": c_false_alarms, "tier_c_safe_batches": c_safe_runs,
        "confusion": {f"{e}->{g}": c for (e, g), c in conf.items()},
        "headline": f"Tier A agrees on {a_ok}/{n}; replay {replay_ok}/{witnesses}"})


if __name__ == "__main__":
    print(main()["headline"])
