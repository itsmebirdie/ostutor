"""Efficiency evaluation (Build Plan 10.2): states explored, time per verdict, memory per
state, scaling against the number of interleavings, and Tier B reduction."""
from __future__ import annotations

import statistics
import time
import tracemalloc

from common import environment, save, table
from dataset import DATASET, ring

from ostutor.dsl.parser import parse
from ostutor.explorer import analyze_full
from ostutor.explorer.model import GModel
from ostutor.explorer.search import explore
from ostutor.ui.viewmodel import interleavings


def measure(program, tier="A", repeats=5, **kw):
    """(states, median ms, peak KiB) for one search. Memory comes from tracemalloc, which
    counts Python allocations only, so it is a lower bound on process memory."""
    times = []
    states = 0
    for _ in range(repeats):
        t0 = time.perf_counter()
        v = analyze_full(program, tier=tier, **kw)[0]
        times.append((time.perf_counter() - t0) * 1000)
        states = v.states_explored
    tracemalloc.start()
    analyze_full(program, tier=tier, **kw)
    peak = tracemalloc.get_traced_memory()[1]
    tracemalloc.stop()
    return states, statistics.median(times), peak / 1024


def main() -> dict:
    per, big = [], []
    for d in DATASET:
        p = parse(d["code"])
        st, ms, kib = measure(p.program, loop_unroll=p.loop_unroll)
        per.append([d["name"], st, f"{ms:.2f}", f"{kib:.0f}", f"{kib * 1024 / max(st, 1):.0f}"])
        big.append((st, ms, kib))

    scale = []
    for n in range(1, 13):
        prog = {"mutexes": [], "shared": ["x"],
                "threads": {"T1": [("read", "x")] * n, "T2": [("read", "x")] * n}}
        t0 = time.perf_counter()
        ex = explore(GModel(prog))
        ms = (time.perf_counter() - t0) * 1000
        sched = interleavings([n, n])
        scale.append([n, f"{sched:,}", len(ex.order), f"{sched / len(ex.order):,.1f}",
                      f"{ms:.2f}"])

    red = []
    for n in (3, 4, 5, 6):
        p = parse(ring(n)).program
        sa, ta, _ = measure(p, "A", repeats=3)
        sb, tb, _ = measure(p, "B", repeats=3)
        red.append([f"dining {n} (deadlock)", sa, sb, f"{sa / sb:.1f}x",
                    f"{ta:.1f}", f"{tb:.1f}"])
    for k in (2, 3, 4, 5):
        p = {"mutexes": ["m"], "shared": ["x"], "threads": {
            f"T{i + 1}": [("lock", "m"), ("read", "x"), ("write", "x"), ("unlock", "m")]
            for i in range(k)}}
        sa, ta, _ = measure(p, "A", repeats=3)
        sb, tb, _ = measure(p, "B", repeats=3)
        red.append([f"{k} identical lockers (safe)", sa, sb, f"{sa / sb:.1f}x",
                    f"{ta:.1f}", f"{tb:.1f}"])

    # state-budget calibration: how fast does the search run, and what does a state cost?
    p = parse(ring(6)).program
    t0 = time.perf_counter()
    ex = explore(GModel(p))
    secs = time.perf_counter() - t0
    big_states = len(ex.order)
    tracemalloc.start()
    explore(GModel(p))
    peak = tracemalloc.get_traced_memory()[1]
    tracemalloc.stop()
    per_state = peak / big_states
    rate = big_states / secs

    md = f"""# Efficiency evaluation

*{environment()}. Generated by `eval/run_efficiency.py`. Times are medians of 5 runs
(3 for the Tier B table); memory is `tracemalloc` peak (Python allocations only).*

## Calibrating the state budget (Build Plan 5.2 asked for this measurement)

On the largest exhaustive search below (dining philosophers, 6 threads: **{big_states:,}
states**) the explorer ran at about **{rate:,.0f} states/second** and used about
**{per_state:,.0f} bytes per state** (peak, including the graph, parents and edges). The
plan's *estimate* was 300 to 600 bytes for the visited set alone; our figure also includes
the edge lists and representatives, so it is not directly comparable. At that cost the
default budget of 300,000 states needs roughly {300_000 * per_state / 2**20:,.0f} MiB and
{300_000 / rate:,.0f} seconds.

## Interleavings versus states (two threads, n read steps each)

{table(["n", "interleavings", "states", "ratio", "ms"], scale)}

## Tier B (symmetry reduction) versus Tier A

{table(["program", "states A", "states B", "reduction", "ms A", "ms B"], red)}

## Per program (all {len(DATASET)} evaluation programs, Tier A)

Median time over all programs: **{statistics.median(b[1] for b in big):.2f} ms**;
largest: {max(b[0] for b in big):,} states.

{table(["program", "states", "ms", "peak KiB", "bytes/state"], per)}
"""
    return save("efficiency", md, {
        "budget_states_per_second": rate, "bytes_per_state": per_state,
        "largest_search_states": big_states, "scaling": scale, "tier_b": red,
        "median_ms_all_programs": statistics.median(b[1] for b in big),
        "headline": f"{rate:,.0f} states/s, {per_state:,.0f} bytes/state at {big_states:,} states"})


if __name__ == "__main__":
    print(main()["headline"])
